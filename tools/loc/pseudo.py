#!/usr/bin/env python3
"""Generates the pseudo-locale (qps-ploc) from the English resource files of both apps.

    python3 tools/loc/pseudo.py            write src/<app>/Strings/qps-ploc/Resources.resw
    python3 tools/loc/pseudo.py --check    exit 1 when a committed qps-ploc file differs from what this script would write

Every ASCII letter becomes an accented letter (so unaccented text on screen is a string that bypassed the resources), the text grows (so truncation and
clipping show up) and the whole string is wrapped in [ ... ]: "Save" becomes "[Šåvé ‹lörém›]". Placeholders such as {0} and {1:N0} are left alone.
The accent can be undone with Unicode normalisation (decompose, drop combining marks), which is how tests/Remotely.Tests/LocalizationPseudoTests.cs checks that the
file really comes from en-US. Windows resolves qps-ploc when the display language list contains it.
"""
import math
import re
import sys
import unicodedata
from pathlib import Path
from xml.etree import ElementTree as ET
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
APPS = ["Remotely.App", "Remotely.ServerManager"]

LOWER = dict(zip("abcdefghijklmnopqrstuvwxyz", "åḃçďéḟĝĥîĵķĺḿñöṕqŕšţüṽŵẋýž"))
UPPER = dict(zip("ABCDEFGHIJKLMNOPQRSTUVWXYZ", "ÅḂÇĎÉḞĜĤÎĴĶĹḾÑÖṔQŔŠŢÜṼŴẊÝŽ"))
ACCENTS = {**LOWER, **UPPER}
FILLER = "lorem ipsum dolor sit amet consectetur adipiscing elit sed do eiusmod tempor incididunt ut labore et dolore magna aliqua "
PLACEHOLDER = re.compile(r"\{[^{}]*\}")


def self_check() -> None:
    for plain, accented in ACCENTS.items():
        decomposed = unicodedata.normalize("NFD", accented)
        base = "".join(c for c in decomposed if not unicodedata.combining(c))
        assert base == plain, f"{accented!r} does not reduce to {plain!r}"


def accent(text: str) -> str:
    out, i = [], 0
    for m in PLACEHOLDER.finditer(text):
        out.append("".join(ACCENTS.get(c, c) for c in text[i:m.start()]))
        out.append(m.group(0))
        i = m.end()
    out.append("".join(ACCENTS.get(c, c) for c in text[i:]))
    return "".join(out)


def growth(length: int) -> float:
    """Short strings grow more than long ones, as real translations do."""
    return 1.0 if length <= 10 else 0.6 if length <= 30 else 0.4


def pseudo(text: str) -> str:
    pad = max(3, math.ceil(len(text) * growth(len(text))))
    filler = accent((FILLER * (pad // len(FILLER) + 1))[:pad].rstrip())
    return f"[{accent(text)} ‹{filler}›]"


def render(app: str) -> str:
    source = ROOT / "src" / app / "Strings" / "en-US" / "Resources.resw"
    lines = source.read_text(encoding="utf-8").splitlines()
    header = []
    for line in lines:
        if line.lstrip().startswith("<data "):
            break
        if line.lstrip().startswith("<!--"):
            continue
        header.append(line)
    header.append("  <!-- GENERATED by tools/loc/pseudo.py from en-US. Do not edit; run the script again. Pseudo-locale: accented, expanded, bracketed. -->")
    body = []
    for data in ET.parse(source).getroot().findall("data"):
        name = data.get("name")
        value = data.findtext("value") or ""
        body.append(f'  <data name="{escape(name)}" xml:space="preserve"><value>{escape(pseudo(value))}</value></data>')
    return "\n".join(header + body + ["</root>", ""])


def main(argv: list[str]) -> int:
    self_check()
    check = "--check" in argv
    stale = []
    for app in APPS:
        target = ROOT / "src" / app / "Strings" / "qps-ploc" / "Resources.resw"
        text = render(app)
        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8", newline="\n")
            print("wrote", target.relative_to(ROOT))
    if stale:
        print("out of date (run python3 tools/loc/pseudo.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

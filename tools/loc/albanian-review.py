#!/usr/bin/env python3
"""Writes docs/albanian-review.md: every Albanian string next to its English original, for a fluent speaker to review.

    python3 tools/loc/albanian-review.py

Who wrote each string is read from git (git blame of the sq-AL line: author and commit), not assumed. A string whose git author is not "Claude" is marked as
such and is not called machine-written. A line that is not committed yet is marked "uncommitted". Git can only say who committed a line, not whether a human
edited it before it was committed; the document says so.
"""
import re
import subprocess
import sys
from pathlib import Path
from xml.etree import ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
APPS = [("Remotely.App", "Remotely (the app on every PC)"), ("Remotely.ServerManager", "Remotely Server Manager")]


def blame(path: Path) -> dict[str, tuple[str, str]]:
    """key -> (author, short commit) for each <data name="key"> line."""
    out = subprocess.run(["git", "blame", "--line-porcelain", "--", str(path.relative_to(ROOT))], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    result, commit, author = {}, "", ""
    for line in out.splitlines():
        if re.match(r"^[0-9a-f]{40} ", line):
            commit = line[:7]
        elif line.startswith("author "):
            author = line[7:]
        elif line.startswith("\t"):
            m = re.search(r'<data name="([^"]+)"', line)
            if m:
                result[m.group(1)] = (author, commit)
    return result


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def placeholders(text: str) -> str:
    return ",".join(sorted(re.findall(r"\{\d+[^{}]*\}", text)))


def main() -> int:
    lines = [
        "# Albanian (sq-AL) review sheet",
        "",
        "Generated by `python3 tools/loc/albanian-review.py`. Do not edit by hand; correct the string in `src/<app>/Strings/sq-AL/Resources.resw` and run the script again.",
        "",
        "How to review: read the English and the Albanian side by side, write the corrected Albanian in the last column (or edit the .resw directly), and keep every `{0}`, `{1}` placeholder.",
        "",
        "**Who wrote these strings.** The *Origin* column is read from `git blame` on the Albanian line; the counts are at the end of this sheet. Git only records who committed a line.",
        "It cannot show whether a person corrected a string before it was committed, so \"machine-written\" here means \"committed by the Claude agent\", and no fluent speaker has",
        "reviewed any of these strings unless this document or the commit history says so.",
        "",
        "**Flags.** `same as English` is expected for brand names, units and format examples and is a problem anywhere else. `Nav_Home` may have a grammatical-gender mismatch (see the notes at the end).",
        "",
    ]
    total = {"machine": 0, "other": 0, "uncommitted": 0}
    for app, title in APPS:
        en = {e.get("name"): (e.findtext("value") or "") for e in ET.parse(ROOT / "src" / app / "Strings" / "en-US" / "Resources.resw").getroot().findall("data")}
        sq_path = ROOT / "src" / app / "Strings" / "sq-AL" / "Resources.resw"
        sq = {e.get("name"): (e.findtext("value") or "") for e in ET.parse(sq_path).getroot().findall("data")}
        who = blame(sq_path)
        lines += [f"## {title}", "", f"{len(sq)} strings.", "", "| Key | English | Albanian | Origin | Flags | Corrected Albanian |", "|---|---|---|---|---|---|"]
        for key, english in en.items():
            albanian = sq.get(key, "")
            author, commit = who.get(key, ("", ""))
            if author == "Claude":
                origin, kind = f"machine-written (git author Claude, {commit})", "machine"
            elif author in ("", "Not Committed Yet"):
                origin, kind = "uncommitted when generated", "uncommitted"
            else:
                origin, kind = f"git author {author} ({commit}); not assumed machine-written", "other"
            total[kind] += 1
            flags = []
            if albanian == english:
                flags.append("same as English")
            if placeholders(english) != placeholders(albanian):
                flags.append("PLACEHOLDERS DIFFER")
            lines.append(f"| `{key}` | {cell(english)} | {cell(albanian)} | {origin} | {', '.join(flags)} | |")
        lines.append("")
    lines += [
        "## Notes for the reviewer",
        "",
        "- `Nav_Home` is \"Kjo rrjet\" (\"This network\"). The agent that wrote this sheet believes `rrjet` is masculine (`ky rrjet`), which would make \"Kjo\" wrong. This is a belief, not a verified fact; please confirm.",
        "- Forms of address: the strings use the polite plural (`ju`, `tuaj`). Confirm that this is the register you want for an app.",
        "- Units in `Duration_*` (`h`, `min`, `s`) are left as in English.",
        "",
        f"Counts at generation time: {total['machine']} machine-written, {total['other']} with another git author, {total['uncommitted']} uncommitted.",
        "",
    ]
    (ROOT / "docs" / "albanian-review.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote docs/albanian-review.md", total)
    return 0


if __name__ == "__main__":
    sys.exit(main())
